"""Bounded DNS wordlist discovery for explicitly registered, owned domains."""
import json
import re
import shutil
import subprocess
import tempfile
import threading
from datetime import datetime, timezone
from pathlib import Path

_LOCK = threading.Lock()
_DOMAIN = re.compile(r'(?=.{1,253}$)(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$')
WORDS = ('www','api','dev','staging','test','mail','smtp','imap','webmail','vpn','admin','portal','app','blog','shop','cdn','static','assets','files','docs','status','monitor','git','ns1','ns2','ftp','sftp','db','database','backup','intranet','beta','auth','login','dashboard','support','help','m','mobile','old','new','prod','www2','api2','gateway','proxy','cache','media','images','mx','remote','office','cloud')

def run_dnsx_brute(host, is_ip, entry):
    host = str(host).lower().rstrip('.')
    if is_ip or not _DOMAIN.fullmatch(host):
        return {'tool':'dnsx_brute','status':'unavailable','detail':'Exige domínio público válido.'}
    if not isinstance(entry, dict) or entry.get('ip','').lower().rstrip('.') != host:
        return {'tool':'dnsx_brute','status':'unavailable','detail':'Domínio não corresponde ao cadastro autorizado.'}
    binary = shutil.which('dnsx')
    if not binary:
        return {'tool':'dnsx_brute','status':'unavailable','detail':'DNSx não encontrado.'}
    if not _LOCK.acquire(blocking=False):
        return {'tool':'dnsx_brute','status':'busy','detail':'Outra descoberta DNS já está em execução.'}
    try:
        with tempfile.TemporaryDirectory(prefix='linuxsec-dnsx-') as tmp:
            wordlist = Path(tmp) / 'words.txt'
            wordlist.write_text('\n'.join(WORDS)+'\n', encoding='utf-8')
            args = [binary,'-d',host,'-w',str(wordlist),'-auto-wildcard','-a','-j','-silent','-t','2','-rl','2','-retry','1','-timeout','3s','-duc']
            try:
                proc = subprocess.run(args, capture_output=True, text=True, stdin=subprocess.DEVNULL, timeout=90, check=False)
            except subprocess.TimeoutExpired:
                return {'tool':'dnsx_brute','status':'timeout','target':host,'detail':'Tempo máximo de 90 segundos atingido.'}
            except OSError as exc:
                return {'tool':'dnsx_brute','status':'failed','target':host,'detail':type(exc).__name__}
        records = {}
        for line in proc.stdout.splitlines()[:300]:
            try:
                item = json.loads(line)
            except (ValueError, TypeError):
                continue
            if not isinstance(item, dict):
                continue
            name = str(item.get('host','')).lower().rstrip('.')
            if not name.endswith('.'+host) or len(name)>253 or not all(re.fullmatch(r'[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?', label) for label in name.split('.')):
                continue
            # Only names generated by this bounded wordlist.
            if name[:-len(host)-1] not in WORDS:
                continue
            records[name] = {'host':name,'a':item.get('a',[]),'rcode':item.get('rcode',item.get('status_code'))}
            if len(records)>=len(WORDS):
                break
        return {'tool':'dnsx_brute','status':'completed' if proc.returncode==0 else 'failed',
                'target':host,'executed_at':datetime.now(timezone.utc).isoformat(),
                'count':len(records),'subdomains':sorted(records), 'records':[records[k] for k in sorted(records)],
                'wordlist_size':len(WORDS),'rate_limit':2,'exit_code':proc.returncode,'stderr':proc.stderr[:1500],
                'notice':'DNS brute force de baixa taxa em domínio cadastrado. Descobertas não autorizam varreduras ativas.'}
    finally:
        _LOCK.release()
